package app.roadbeacon.nostr

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Runs `nips/vectors/road-events-v1.json`, the vectors both clients are tested against. They were
 * generated by an independent implementation (`tools/gen_road_event_vectors.py`, real BIP-340
 * signatures), so passing them means agreeing with Roadstr byte for byte.
 *
 * This codec reports a refusal as null, not by name; the error names are checked by Roadstr's
 * suite. Signatures are checked here with [EventSigner.verify], as the relay and radio paths do.
 */
class ConformanceVectorsTest {

    private val json = Json { ignoreUnknownKeys = true }
    private val vectors: JsonObject = json.parseToJsonElement(
        javaClass.classLoader!!.getResource("road-events-v1.json")!!.readText()
    ).jsonObject

    private fun list(name: String) = vectors[name]!!.jsonArray.map { it.jsonObject }

    private fun JsonObject.event(): NostrEvent = json.decodeFromJsonElement(NostrEvent.serializer(), this["event"]!!)

    private fun JsonObject.frame(): ByteArray = this["frame"]!!.jsonPrimitive.content.hexToBytes()

    private fun JsonObject.name(): String = this["name"]!!.jsonPrimitive.content

    private fun encode(event: NostrEvent): ByteArray? = when (event.kind) {
        1315 -> BinaryCodec.encodeReport(event)
        1316 -> BinaryCodec.encodeConfirmation(event)
        else -> null
    }

    @Test
    fun `limits match the codec`() {
        val limits = vectors["limits"]!!.jsonObject
        assertEquals(limits["report_base"]!!.jsonPrimitive.int, BinaryCodec.REPORT_BASE_SIZE)
        assertEquals(limits["report_max_encode"]!!.jsonPrimitive.int, BinaryCodec.REPORT_MAX_SIZE)
        assertEquals(limits["report_max_decode"]!!.jsonPrimitive.int, BinaryCodec.REPORT_MAX_DECODED_SIZE)
        assertEquals(limits["vote"]!!.jsonPrimitive.int, BinaryCodec.CONFIRMATION_SIZE)
    }

    @Test
    fun `valid events encode to the exact frame and decode back to the exact event`() {
        for (vector in list("valid")) {
            val event = vector.event()
            val frame = vector.frame()
            assertTrue(vector.name(), EventSigner.verify(event))
            assertTrue(vector.name(), BinaryCodec.isCanonical(event))
            assertArrayEquals(vector.name(), frame, encode(event))

            val decoded = BinaryCodec.decode(frame)
            assertEquals(vector.name(), event, decoded)
            assertTrue(vector.name(), EventSigner.verify(decoded!!))
        }
    }

    @Test
    fun `decode-only frames are accepted but never produced`() {
        for (vector in list("decode_only")) {
            val event = vector.event()
            val decoded = BinaryCodec.decode(vector.frame())
            assertEquals(vector.name(), event, decoded)
            assertTrue(vector.name(), EventSigner.verify(decoded!!))
            if (event.content.toByteArray(Charsets.UTF_8).size > RoadEventFormat.MAX_COMMENT_BYTES) {
                assertNull(vector.name(), encode(event))
            }
        }
    }

    @Test
    fun `invalid frames are refused`() {
        for (vector in list("decode_invalid")) {
            val decoded = BinaryCodec.decode(vector.frame())
            if (vector["error"]!!.jsonPrimitive.content == "SIGNATURE_INVALID") {
                // Decoding does not verify; the caller must, and must then drop it.
                assertNotNull(vector.name(), decoded)
                assertFalse(vector.name(), EventSigner.verify(decoded!!))
            } else {
                assertNull(vector.name(), decoded)
            }
        }
    }

    @Test
    fun `invalid events are refused by the encoder or fail verification`() {
        for (vector in list("encode_invalid")) {
            val event = vector.event()
            if (vector["error"]!!.jsonPrimitive.content == "SIGNATURE_INVALID") {
                assertFalse(vector.name(), EventSigner.verify(event))
            } else {
                assertNull(vector.name(), encode(event))
            }
        }
    }
}

private fun String.hexToBytes(): ByteArray =
    chunked(2).map { it.toInt(16).toByte() }.toByteArray()
